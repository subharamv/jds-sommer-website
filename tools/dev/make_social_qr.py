"""Footer social icons show a QR code on hover (desktop), so visitors can open the profile on their phone.

The QR codes are generated here once and written into assets/js/main.js (between the
"social-qr" markers), so the site needs no QR library at runtime and no third-party QR service.
Each entry is [size in modules, path of the data modules]. The three corner "eyes" (rounded, red centre)
and the platform icon in the middle are drawn by main.js, so they are left out of the path here.
Error correction is Q (25 %), which leaves room for the icon in the middle.
Run again after a social link in the footer changes:  python tools/dev/make_social_qr.py
(needs: pip install segno)
"""
import json, os, re
import segno

SITE = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
JS = os.path.join(SITE, 'assets', 'js', 'main.js')
BADGE = 8 / 33   # icon badge size as a share of the code width (keep in sync with main.js), so every code shows the same icon size

footer = open(os.path.join(SITE, 'en', 'index.html'), encoding='utf-8').read()
ul = re.search(r'<ul class="social social--footer".*?</ul>', footer, re.S).group(0)
urls = re.findall(r'href="(https?://[^"]+)"', ul)


def data_path(url):
    m = [list(r) for r in segno.make(url, error='q', micro=False).matrix]
    n = len(m)
    centre = int(n * BADGE + 1)          # modules left free for the badge: odd, so the free square is centred
    centre += 1 - centre % 2
    c0 = (n - centre) // 2
    eyes = [(0, 0), (n - 7, 0), (0, n - 7)]
    def free(x, y):
        if any(ex <= x < ex + 7 and ey <= y < ey + 7 for ex, ey in eyes):
            return False
        return not (c0 <= x < c0 + centre and c0 <= y < c0 + centre)
    d = []
    for y in range(n):
        x = 0
        while x < n:
            if m[y][x] and free(x, y):
                s = x
                while x < n and m[y][x] and free(x, y):
                    x += 1
                d.append(f'M{s} {y}h{x - s}v1h-{x - s}z')
            else:
                x += 1
    return [n, ''.join(d)]


qr = {url: data_path(url) for url in urls}
block = '  // social-qr: generated by tools/dev/make_social_qr.py, do not edit by hand\n  var QR = ' + json.dumps(qr, indent=1).replace('\n', '\n  ') + ';\n  // /social-qr'
s = open(JS, encoding='utf-8', newline='').read()
nl = '\r\n' if '\r\n' in s else '\n'
s, n = re.subn(r'  // social-qr:.*?// /social-qr', lambda _: block.replace('\n', nl), s, count=1, flags=re.S)
assert n == 1, 'no social-qr markers in main.js'
open(JS, 'w', encoding='utf-8', newline='').write(s)
print('QR codes:', ', '.join(f'{u} ({qr[u][0]} modules)' for u in urls))
